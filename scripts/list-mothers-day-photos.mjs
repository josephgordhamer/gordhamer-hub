#!/usr/bin/env node
// Scans public/mothers-day at build time and writes a TypeScript module
// listing the photos. This runs in `prebuild` so Vercel always has an
// up-to-date list without relying on fs at request time.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const dir = path.join(root, "public", "mothers-day");
const outDir = path.join(
  root,
  "src",
  "app",
  "(authed)",
  "celebrations",
  "mothers-day-2026",
);
const outFile = path.join(outDir, "photos.generated.ts");

let files = [];
try {
  files = fs
    .readdirSync(dir)
    .filter((f) => /\.(jpg|jpeg|png|webp)$/i.test(f))
    .sort();
} catch {
  console.warn("[mothers-day] public/mothers-day not found — generating empty list");
}

const heroIdx = files.findIndex((f) => /^hero\./i.test(f));
const heroName = heroIdx >= 0 ? files[heroIdx] : files[0] ?? null;
const collage = files.filter((f) => f !== heroName);

const toSrc = (name) => `/mothers-day/${encodeURIComponent(name)}`;

const heroExport = heroName ? JSON.stringify(toSrc(heroName)) : "null";
const collageExport = JSON.stringify(collage.map(toSrc), null, 2);

const content = `// AUTO-GENERATED by scripts/list-mothers-day-photos.mjs — do not edit by hand.
// Re-run \`npm run prebuild\` (or any \`npm run build\`) to regenerate after
// adding or removing files in public/mothers-day/.

export const HERO_PHOTO: string | null = ${heroExport};

export const COLLAGE_PHOTOS: readonly string[] = ${collageExport} as const;
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, content);
console.log(
  `[mothers-day] wrote ${files.length} photo${files.length === 1 ? "" : "s"} ` +
    `to ${path.relative(root, outFile)}`,
);
